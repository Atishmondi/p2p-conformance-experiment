"""Independent small traces: catch first-event shortcuts and invented evidence."""
import csv
import importlib.util
import sys
import subprocess
import tempfile
import unittest
from datetime import datetime, timezone
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'src'))
import check_conformance as checker

AP, PO, REC, INV, PAY, MOD = ('Purchase Request Approval', 'Purchase Order',
                             'Goods Receipt', 'Vendor Invoice', 'Payment', 'PO Modification')


def event(activity, day, **fields):
    row = {'case_id': 'C1', 'activity': activity,
           'timestamp': '2026-01-%02dT10:00:00' % day}
    row.update(fields)
    return row


def trace(*rows):
    # The historical callable accepts parsed timestamps. Expectations below
    # are literal, hand-calculated results, never generated by the checker.
    return [dict(row, _ts=datetime.fromisoformat(row['timestamp']),
                 **{key: Decimal(str(row[key])) for key in ('qty_received', 'qty_invoiced')
                    if key in row}) for row in rows]


class RuleTests(unittest.TestCase):
    def rules(self, *rows):
        return checker.check_case(trace(*rows))[0]

    def test_cumulative_invoices_cannot_reuse_one_receipt(self):
        rules = self.rules(event(REC, 1, qty_received='10'),
                           event(INV, 2, qty_invoiced='6'), event(INV, 3, qty_invoiced='6'))
        self.assertIs(rules['R3'], True)

    def test_multiple_receipts_are_event_deltas(self):
        result = checker.check_case(trace(event(REC, 1, qty_received='3.25'),
                                          event(REC, 2, qty_received='6.75'),
                                          event(INV, 3, qty_invoiced='10')))
        self.assertIs(result[0]['R3'], False)
        self.assertEqual(result[5:], (Decimal('10.00'), Decimal('10')))

    def test_later_receipt_does_not_fix_earlier_invoice(self):
        rules = self.rules(event(INV, 1, qty_invoiced='10'), event(REC, 2, qty_received='10'))
        self.assertIs(rules['R2'], True)
        self.assertIs(rules['R3'], True)

    def test_snapshot_quantities_on_other_activities_are_ignored(self):
        rules = self.rules(event(PO, 1, qty_received='100', qty_invoiced='100'),
                           event(REC, 2, qty_received='2', qty_invoiced='100'),
                           event(INV, 3, qty_received='100', qty_invoiced='3'))
        self.assertIs(rules['R3'], True)

    def test_missing_and_empty_evidence_is_unknown(self):
        self.assertEqual(checker.check_case([])[0],
                         {'R1': None, 'R2': None, 'R3': None, 'R4': False, 'R5': None})
        rules = self.rules(event(PO, 1), event(INV, 2), event(PAY, 3))
        self.assertIsNone(rules['R1'])
        self.assertIsNone(rules['R2'])
        self.assertIsNone(rules['R3'])
        self.assertIs(rules['R5'], False)

    def test_missing_quantity_is_unknown_and_proven_violation_dominates(self):
        self.assertIsNone(self.rules(event(REC, 1), event(INV, 2, qty_invoiced='2'))['R3'])
        self.assertIs(self.rules(event(REC, 1, qty_received='1'),
                                 event(INV, 2, qty_invoiced='2'), event(INV, 3))['R3'], True)

    def test_unknown_invoice_cannot_erase_known_excess(self):
        self.assertIs(self.rules(event(REC, 1, qty_received='1'), event(INV, 2),
                                 event(INV, 3, qty_invoiced='2'))['R3'], True)

    def test_tied_order_is_unknown_independent_of_csv_row_order(self):
        for rows in ((event(AP, 1), event(PO, 1)), (event(PO, 1), event(AP, 1))):
            self.assertIsNone(self.rules(*rows)['R1'])
        self.assertIsNone(self.rules(event(REC, 1, qty_received='10'),
                                     event(INV, 1, qty_invoiced='10'))['R2'])
        self.assertIsNone(self.rules(event(REC, 1, qty_received='10'),
                                     event(INV, 1, qty_invoiced='10'))['R3'])
        self.assertIsNone(self.rules(event(INV, 1), event(PAY, 1))['R5'])
        self.assertIs(self.rules(event(REC, 1, qty_received='1'),
                                 event(INV, 1, qty_invoiced='2'))['R3'], True)

    def test_every_target_event_is_checked(self):
        self.assertIs(self.rules(event(PO, 1), event(AP, 2), event(PO, 3))['R1'], True)
        self.assertIs(self.rules(event(PAY, 1), event(INV, 2), event(PAY, 3))['R5'], True)
        self.assertIs(self.rules(event(INV, 1), event(REC, 2), event(INV, 3))['R2'], True)

    def test_reapproval_is_between_each_modification_and_next_po(self):
        rows = (event(AP, 1), event(PO, 2), event(MOD, 3),
                event('Purchase Request Approval (re-approval)', 4), event(PO, 5))
        self.assertIs(self.rules(*rows)['R4'], False)
        self.assertIs(self.rules(event(AP, 1), event(MOD, 2), event(PO, 3))['R4'], True)
        self.assertIsNone(self.rules(event(MOD, 1), event(AP, 2))['R4'])
        self.assertIsNone(self.rules(event(MOD, 1), event(AP, 1), event(PO, 2))['R4'])
        self.assertIsNone(self.rules(event(MOD, 1), event(AP, 2), event(PO, 2))['R4'])


class InputTests(unittest.TestCase):
    def load(self, rows, fields=None):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / 'events.csv'
            names = fields or sorted({key for row in rows for key in row})
            with path.open('w', newline='') as handle:
                writer = csv.DictWriter(handle, fieldnames=names)
                writer.writeheader()
                writer.writerows(rows)
            return checker.load(path)

    def test_minimal_schema_and_optional_quantities(self):
        result = self.load([event(REC, 1), event(INV, 2, qty_invoiced='0.1')])
        self.assertIsNone(result['C1'][0]['qty_received'])
        self.assertEqual(result['C1'][1]['qty_invoiced'], Decimal('0.1'))
        self.assertIsNone(checker.check_case(result['C1'])[0]['R3'])

    def test_invalid_quantities_rejected(self):
        for quantity in ('oops', '-1', 'NaN', 'Infinity', '-Infinity'):
            with self.subTest(quantity=quantity), self.assertRaises(ValueError):
                self.load([event(REC, 1, qty_received=quantity)])

    def test_exact_decimal_comparison(self):
        result = self.load([event(REC, 1, qty_received='0.1'),
                            event(REC, 2, qty_received='0.2'), event(INV, 3, qty_invoiced='0.3')])
        self.assertIs(checker.check_case(result['C1'])[0]['R3'], False)
        excess = self.load([event(REC, 1, qty_received='0.3'),
                            event(INV, 2, qty_invoiced='0.30000000000000000001')])
        self.assertIs(checker.check_case(excess['C1'])[0]['R3'], True)

    def test_missing_required_schema_and_empty_required_values_rejected(self):
        for key in ('case_id', 'activity', 'timestamp'):
            row = event(REC, 1)
            row.pop(key)
            with self.subTest(missing=key), self.assertRaises(ValueError):
                self.load([row])
            row[key] = ''
            with self.subTest(blank=key), self.assertRaises(ValueError):
                self.load([row])

    def test_timestamp_validation_and_utc_normalization(self):
        row = event(REC, 1)
        row['timestamp'] = '2026-01-01T12:00:00+02:00'
        result = self.load([row])
        self.assertEqual(result['C1'][0]['_ts'], datetime(2026, 1, 1, 10, tzinfo=timezone.utc))
        for stamp in ('bad-date', '2026-01-01'):
            with self.subTest(stamp=stamp), self.assertRaises(ValueError):
                self.load([dict(row, timestamp=stamp)])
        with self.assertRaises(ValueError):
            self.load([row, event(INV, 2)])

    def test_duplicate_ids_and_exact_anonymous_events_rejected(self):
        for rows in ([event(REC, 1), event(REC, 1)],
                     [event(REC, 1, event_id='E1'), event(INV, 2, event_id='E1')]):
            with self.subTest(rows=rows), self.assertRaises(ValueError):
                self.load(rows)

    def test_conflicting_product_or_unit_rejected(self):
        for field in ('product_id', 'unit'):
            with self.subTest(field=field), self.assertRaises(ValueError):
                self.load([event(REC, 1, **{field: 'A'}), event(INV, 2, **{field: 'B'})])

    def test_returns_and_reversals_rejected(self):
        for activity in ('Goods Return', 'Receipt Reversal', 'Credit Note', 'Invoice Reversal'):
            with self.subTest(activity=activity), self.assertRaises(ValueError):
                self.load([event(activity, 1)])


class ReportTests(unittest.TestCase):
    def test_unknown_rows_are_not_reported_as_compliant(self):
        with tempfile.TemporaryDirectory() as directory:
            output = checker.write_results({'C1': trace(event(PO, 1))}, Path(directory), 'fixture')
            self.assertEqual(set(output), {'conformance', 'summary'})
            with output['conformance'].open(newline='') as handle:
                row = next(csv.DictReader(handle))
            self.assertEqual(row['rule_version'], 'v2')
            self.assertEqual(row['status'], 'not_evaluable')
            self.assertEqual(row['violations'], '')
            self.assertEqual(row['not_evaluable'], 'R1;R2;R3;R5')
            with output['summary'].open(newline='') as handle:
                summary = next(csv.DictReader(handle))
            self.assertEqual((summary['compliant'], summary['violating'], summary['not_evaluable']),
                             ('0', '0', '1'))
            self.assertEqual(summary['conformance_rate'], '')

    def test_canonical_v1_and_v2_baseline_counts(self):
        historical = ROOT / 'src' / 'legacy' / 'check_conformance_v1.py'
        self.assertTrue(historical.exists(), 'historical v1 checker snapshot is required')
        spec = importlib.util.spec_from_file_location('checker_v1', historical)
        legacy = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(legacy)
        for era, total, bad in (('r1', 120, 60), ('r2', 60, 0)):
            path = ROOT / 'data' / ('event-log-%s.csv' % era)
            for implementation in (legacy, checker):
                with self.subTest(era=era, version=implementation.__name__):
                    cases = implementation.load(path)
                    self.assertEqual(len(cases), total)
                    self.assertEqual(sum(any(v is True for v in implementation.check_case(evs)[0].values())
                                         for evs in cases.values()), bad)
                    self.assertFalse(any(v is None for evs in cases.values()
                                         for v in implementation.check_case(evs)[0].values()))


class NoiseConsumerTests(unittest.TestCase):
    def test_noise_consumer_uses_shared_unknown_rules_without_optional_dependencies(self):
        script = """
import sys
sys.path.insert(0, 'src')
import noise_test
from check_conformance import check_case
assert noise_test.check_case is check_case
failed, full = noise_test.eval_cases({'empty': []})
assert failed['empty'] == []
assert full['empty'] == {'R1': None, 'R2': None, 'R3': None, 'R4': False, 'R5': None}
assert noise_test.case_status(full['empty']) == 'not_evaluable'
from datetime import datetime
rows = [
    {'case_id': 'C1', 'scenario': 'S1', 'activity': activity,
     'timestamp': '2026-01-%02dT10:00:00' % day,
     'qty_received': '1', 'qty_invoiced': '1'}
    for day, activity in enumerate(('Purchase Request Approval', 'Purchase Order',
                                    'Goods Receipt', 'Vendor Invoice', 'Payment'), 1)]
cases = {'C1': rows}
results = noise_test.run_sweep(cases, levels=(0, 1), seeds=(1,))
assert results[0]['s1_evaluated'] == 1 and results[0]['fpr'] == 0
assert results[1]['s1_evaluated'] == 0 and results[1]['s1_not_evaluable'] == 1
assert results[1]['fpr'] is None

"""
        result = subprocess.run([sys.executable, '-S', '-c', script], cwd=str(ROOT),
                                text=True, capture_output=True)
        self.assertEqual(result.returncode, 0, result.stderr)


